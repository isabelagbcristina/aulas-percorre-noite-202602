// Era uma vez os LAÇOS de repetição da Lógica de programação e o LAÇO FOR era o mais utilizado por economizar espaços e trazer pratiididade para o desenvolvimento.

// Para utilizar o FOR é necessário ter um contador para que delimitemos a quantidade de vezes que algo será repetido. A estrutura do FOR recebe inicialização, condição e incremento.

console.log("Vou contar até 10 e depois dizer UVA");

// inicialização   condição    incremento
for (let i = 1;    i <= 10;       i += 2) {
console.log(i);

console.log("UVA!!!");
}
